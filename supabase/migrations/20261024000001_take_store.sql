-- Piano Arcade take store. Applied to the piano-arcade Supabase project on Oct 24 2026.
-- Shapes mirror the core-loop contracts (Chart, Take, Results). Raw Take and Results are kept verbatim
-- so old takes can be re-judged when the judging rule or the contracts change.
-- Only Next.js server routes write, with the secret key (service_role, bypasses RLS), after re-judging
-- the Take themselves. The publishable key (anon) can read nothing but songs.

create extension if not exists pgcrypto;

-- A player is a random UUID + nickname. No PII, no accounts. The browser keeps a random token;
-- only its SHA-256 lands here. Server routes check it before returning a player's history.
create table public.players (
  id          uuid primary key default gen_random_uuid(),
  handle      text check (handle ~ '^[A-Za-z0-9_ ]{1,16}$'),
  token_sha256 bytea not null unique check (octet_length(token_sha256) = 32),
  created_at  timestamptz not null default now()
);

-- One row per chart.json, upserted by the server from web/public/songs/.
create table public.songs (
  id            text primary key check (id ~ '^[a-z0-9-]{1,64}$'),
  title         text not null,
  composer      text not null,
  bpm           numeric not null check (bpm > 0),
  beats_per_bar int  not null check (beats_per_bar between 1 and 16),
  note_count    int  not null check (note_count > 0),
  chart_sha256  text not null,            -- current version of the chart file
  updated_at    timestamptz not null default now()
);

create table public.takes (
  id                uuid primary key,     -- generated by the browser: retries upsert, never duplicate
  player_id         uuid not null references public.players(id) on delete cascade,
  song_id           text not null references public.songs(id),
  chart_sha256      text not null,        -- chart version this take was judged against
  judge_version     int  not null,        -- bumps when the judging rule changes
  contract_version  int  not null,        -- bumps when Take/Results shapes change
  started_at        timestamptz not null,
  input_device      text not null check (input_device in ('midi','keys')),  -- 'test' never stored
  latency_offset_ms int  not null check (latency_offset_ms between -150 and 150),
  bar_from          int,                  -- null = whole song; set by bar-loop drills
  bar_to            int,
  tempo_pct         int  not null default 100 check (tempo_pct between 25 and 200),
  perfect           int  not null check (perfect >= 0),
  great             int  not null check (great >= 0),
  miss              int  not null check (miss >= 0),
  extras            int  not null check (extras >= 0),
  accuracy          numeric(5,4) not null check (accuracy between 0 and 1),
  max_combo         int  not null check (max_combo >= 0),
  rank              text not null check (rank in ('S','A','B','C','D')),
  take              jsonb not null,       -- Take contract, verbatim
  results           jsonb not null,       -- Results contract, as re-judged on the server
  created_at        timestamptz not null default now(),
  check ((bar_from is null) = (bar_to is null)),
  check (bar_from is null or (bar_from >= 1 and bar_to >= bar_from))
);
create index takes_player_song_time on public.takes (player_id, song_id, created_at desc);
create index takes_song_full on public.takes (song_id, accuracy desc) where bar_from is null and tempo_pct = 100;

-- One row per chart note per take: the grain the coach and progress queries group by.
create table public.note_judgments (
  take_id     uuid not null references public.takes(id) on delete cascade,
  note_id     text not null,
  pitch       int  not null check (pitch between 21 and 108),
  hand        text not null check (hand in ('R','L')),
  bar         int  not null check (bar >= 1),
  beat        numeric not null,
  judgment    text not null check (judgment in ('PERFECT','GREAT','MISS')),
  offset_ms   numeric check (offset_ms between -50 and 50),   -- signed: negative = early
  velocity    int check (velocity between 1 and 127),
  primary key (take_id, note_id),
  check ((judgment = 'MISS') = (offset_ms is null))
);
create index note_judgments_bar on public.note_judgments (take_id, bar);

-- What the coach said, and the exact summary its claims were checked against (mission.md rule).
create table public.coach_feedback (
  id           uuid primary key default gen_random_uuid(),
  player_id    uuid not null references public.players(id) on delete cascade,
  song_id      text not null references public.songs(id),
  take_ids     uuid[] not null check (cardinality(take_ids) between 1 and 20),
  summary      jsonb not null,            -- deterministic numbers given to the model
  report       text not null,             -- what the player was shown
  drill        jsonb,                     -- { from, to, tempo } or null
  verified     boolean not null,          -- false = model failed the check, plain summary shown
  model        text not null,             -- provider-neutral label, e.g. 'gemini-x'
  created_at   timestamptz not null default now()
);
create index coach_feedback_player_song on public.coach_feedback (player_id, song_id, created_at desc);

-- Per bar over a player's last 5 takes of a song (full song or drill). Real counts only.
create view public.bar_trends with (security_invoker = true) as
with recent as (
  select id, player_id, song_id,
         row_number() over (partition by player_id, song_id order by created_at desc) as n
  from public.takes
)
select r.player_id, r.song_id, j.bar,
       count(*)                                    as notes,
       count(*) filter (where j.judgment = 'MISS') as misses,
       round(avg(j.offset_ms), 1)                  as mean_offset_ms,  -- + late, - early
       round(stddev_samp(j.offset_ms), 1)          as spread_ms,
       round(avg(j.velocity))                      as mean_velocity
from recent r join public.note_judgments j on j.take_id = r.id
where r.n <= 5
group by r.player_id, r.song_id, j.bar;

-- One row per take: the progress chart's data.
create view public.take_history with (security_invoker = true) as
select t.player_id, t.song_id, t.id as take_id, t.created_at, t.accuracy, t.rank, t.miss,
       t.bar_from, t.bar_to, t.tempo_pct,
       (select round(avg(abs(j.offset_ms)), 1) from public.note_judgments j where j.take_id = t.id) as mean_abs_offset_ms,
       (select round(stddev_samp(j.offset_ms), 1) from public.note_judgments j where j.take_id = t.id) as spread_ms
from public.takes t;

-- Atomic, idempotent save: take + its note rows in one transaction. Called by the server only.
create function public.save_take(p_take jsonb, p_notes jsonb) returns uuid
language plpgsql security invoker set search_path = public as $$
begin
  insert into takes select * from jsonb_populate_record(null::takes, p_take)
  on conflict (id) do nothing;
  if not found then return (p_take->>'id')::uuid; end if;   -- retry of a saved take
  insert into note_judgments select * from jsonb_populate_recordset(null::note_judgments, p_notes);
  return (p_take->>'id')::uuid;
end $$;
revoke execute on function public.save_take(jsonb, jsonb) from public, anon, authenticated;

-- RLS on everything. No policies for anon except songs: player data is reachable only through server routes.
alter table public.players        enable row level security;
alter table public.songs          enable row level security;
alter table public.takes          enable row level security;
alter table public.note_judgments enable row level security;
alter table public.coach_feedback enable row level security;
create policy "songs are public" on public.songs for select to anon, authenticated using (true);
revoke all on public.players, public.takes, public.note_judgments, public.coach_feedback,
              public.bar_trends, public.take_history from anon, authenticated;
revoke insert, update, delete, truncate on public.songs from anon, authenticated;
grant select on public.songs to anon, authenticated;

-- With "Automatically expose new tables" off, nothing is granted by default: give the server role what it needs.
grant usage on schema public to service_role;
grant select, insert, update, delete on all tables in schema public to service_role;
grant execute on function public.save_take(jsonb, jsonb) to service_role;
